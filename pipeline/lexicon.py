"""Motif lexicon: the concrete things a collector would underline.

Each entry: lemma -> (category, forms, compound, accept)
  forms     whole-word forms that count as a mention
  compound  if True, a word *ending* in one of the forms also counts
            (spookhond, doodskist, wisseldaalder)
  accept    extra answers the typewriter takes for this lemma
The category feeds the first-level hint ("een dier", "een plek", ...).
"""

